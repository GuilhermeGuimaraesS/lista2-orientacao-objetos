package questao05.entities;

public class Calculadora {

    public static int somar(int numero01, int numero02){
        return (numero01 + numero02);
    }

    public static double somar(double numero01, double numero02){
        return (numero01 + numero02);
    }

    public static int somar(int numero01, int numero02, int numero03){
        return (numero01 + numero02 + numero03);
    }

}
